def shell_parts():
    """
    The CSP and the theme line, read out of index.html rather than
    written again here: the policy allows that script by its hash, so
    a copy that drifted by one byte would stop running.
    """
    index = (ROOT / 'index.html').read_text(encoding='utf-8')
    csp = re.search(r'<meta http-equiv="Content-Security-Policy"[^>]*>', index).group(0)
    theme = re.search(r'<script>\n(.*?)</script>', index, re.S).group(0)
    return csp, theme


