#!/usr/bin/env python3
"""
Static pages for search engines, generated from data/rdr2.db.

The app is one page that builds everything in the browser from a SQLite
file, behind a `#` in the address -- which a search engine reads as one
empty page.  This writes a plain HTML page for every material and every
recipe, at an address of its own, carrying the same facts the app's
cards do, so "perfect beaver pelt rdr2" has somewhere to land:

    materials/<slug>/index.html     one per ingredient
    recipes/<slug>/index.html       one per recipe
    materials/index.html            every material, A-Z, by kind
    recipes/index.html              every recipe, A-Z, by vendor
    sitemap.xml

Each page links on into the app, to the same card (#/materials/<id>),
for everything the app does that a page cannot: what you have, what you
still need, crafting.  The slug is the id without its prefix
(ing-perfect-beaver-pelt -> perfect-beaver-pelt), so an address stays
put when a name is corrected, and sw.js can turn one back into its id.

No JavaScript runs on these pages beyond the theme line every page
starts with, and every link in them is relative, so they work wherever
the site is served.  The one absolute address is SITE_URL, for the
canonical links and the sitemap.

Like rdr2.db, the output is generated and committed: run this after
every rebuild of the database.

    python3 scripts/build_pages.py            # write the pages
    python3 scripts/build_pages.py --check    # exit 1 if they are stale
"""

