STATION_PROSE = {
    'station-pearson': 'Pearson', 'station-trapper': 'the Trapper',
    'station-fence': 'the Fence', 'station-campfire': 'your campfire',
}


# ------------------------------------------------------------
# small helpers, mirroring render.js
# ------------------------------------------------------------

def esc(value):
    return html.escape('' if value is None else str(value), quote=True)


def slug(id_, kind):
    return id_[len(PREFIX[kind]):]


def money(cents):
    return f'${cents / 100:.2f}'


def plural(n, word):
    return f'{n} {word}{"" if n == 1 else "s"}'


def listing(items):
    """'a', 'a and b', 'a, b and c'."""
    items = list(items)
    if len(items) < 2:
        return ''.join(items)
    return ', '.join(items[:-1]) + ' and ' + items[-1]


def icon(name):
    return f'<span class="icon icon-{name}" aria-hidden="true"></span>' if name else ''


def stars(quality):
    if not quality:
        return ''
    q = esc(quality)
    return (f'<span class="stars stars-{q.lower()}" role="img" '
            f'aria-label="{q}" title="{q}"></span>')


def quality_label(quality):
    if not quality:
        return ''
    return f'<span class="stars stars-{esc(quality.lower())}" aria-hidden="true"></span>{esc(quality)}'


def web_link(url, text):
    """Only a web address becomes a link, as in render.js."""
    if not re.match(r'^https?://', url or '', re.I):
        return esc(text)
    return (f'<a class="xlink" href="{esc(url)}" target="_blank" rel="noopener noreferrer" '
            f'title="{esc(text)} on the Red Dead wiki">{esc(text)}</a>')


def page_link(kind, id_, text, root):
    return f'<a class="xlink" href="{root}{kind}/{slug(id_, kind)}/">{esc(text)}</a>'


def traits(pairs):
    shown = [(label, value) for label, value in pairs if value]
    if not shown:
        return ''
    rows = ''.join(f'\n        <div class="trait"><dt>{esc(label)}</dt><dd>{value}</dd></div>'
                   for label, value in shown)
    return f'\n      <dl class="traits">{rows}\n      </dl>'


def section(title, body):
    if not body:
        return ''
    return (f'\n      <section class="detail-section">\n'
            f'        <h2 class="list-label">{esc(title)}</h2>\n'
            f'        {body}\n      </section>')


def buff_lines(description):
    return [line.strip() for line in (description or '').split('\n') if line.strip()]


def buff_line(line):
    at = line.rfind(':')
    if at < 1 or at == len(line) - 1:
        return f'<span class="stat">{esc(line)}</span>'
    return (f'<span class="stat">{esc(line[:at])}</span> '
            f'<span class="value">{esc(line[at + 1:].strip())}</span>')


def a_or_an(word):
    return f'{"an" if word[:1].lower() in "aeiou" else "a"} {word}'


def clip(text, limit=158):
    """
    A meta description: whole words, under the length a result shows,
    and a real dash -- the app's typewriter `--` reads as a typo in a
    search result.
    """
    text = ' '.join(text.replace(' -- ', ' – ').split())
    if len(text) <= limit:
        return text
    return text[:limit - 1].rsplit(' ', 1)[0].rstrip(',;:') + '…'


