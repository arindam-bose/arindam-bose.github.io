def recipe_page(r, data, parts):
    root = '../../'
    ingredients = data['ingredients_of'][r['id']]
    groups = slots(r, ingredients)
    campfire = bool(r['repeatable'])
    buffs = buff_lines(r['description'])
    name = r['name']

    def slot_text(options):
        if len(options) == 1:
            return f'{options[0]["qty"]} {options[0]["name"]}'
        return f'{options[0]["qty"]} of any of ' + ' / '.join(o['name'] for o in options)

    def slot_line(options):
        if len(options) == 1:
            o = options[0]
            return (f'\n          <li><span class="qty">{o["qty"]}x</span>'
                    f'<span class="what">{page_link("materials", o["ingredient_id"], o["name"], root)}'
                    f'{stars(o["quality"])}</span></li>')
        names = ' / '.join(page_link('materials', o['ingredient_id'], o['name'], root) for o in options)
        return (f'\n          <li class="any"><span class="qty">{options[0]["qty"]}x</span>'
                f'<span class="what"><span class="any-of">any of</span> {names}</span></li>')

    needs = listing(slot_text(s) for s in groups)
    if campfire:
        intro = (f'{name} is a campfire recipe in Red Dead Redemption 2, made at your own '
                 f'campfire as often as you have the ingredients. It takes {needs}.')
        if r['price_cents']:
            intro += f' The recipe itself costs {money(r["price_cents"])}.'
    else:
        what = a_or_an((r['category'] or 'item').lower())
        intro = (f'{name} is {what} crafted by {STATION_PROSE[r["station_id"]]} '
                 f'in Red Dead Redemption 2. It takes {needs}')
        intro += f' and costs {money(r["price_cents"])}.' if r['price_cents'] else '.'
        if r['set_name']:
            intro += f' Part of {r["set_name"]}.'

    facts = ([('Type', esc(r['category'])),
              ('Made at', f'{icon("campfire")}{esc(r["station"])}'),
              ('Recipe cost', r['price_cents'] and money(r['price_cents']))]
             if campfire else
             [('Type', esc(r['category'])),
              ('Vendor', f'{icon(STATION_ICON.get(r["station_id"]))}{esc(r["station"])}'),
              ('Set', esc(r['set_name'])),
              ('Price', r['price_cents'] and money(r['price_cents']))])

    buff_list = buffs and ('<ul class="detail-list detail-buffs">' + ''.join(
        f'\n          <li>{buff_line(b)}</li>' for b in buffs) + '\n        </ul>')
    choice = len(ingredients) > len(groups)
    ingredient_list = ('<ul class="ingredients detail-ingredients">'
                       + ''.join(slot_line(s) for s in groups) + '\n        </ul>'
                       + ('\n        <p class="hint">"Any of" means all of one kind: the amount '
                          'cannot be made up from a mix.</p>' if choice else ''))

    body = f'''
  <article class="static-detail">
    <header class="detail-head">
      <div>
        <p class="detail-kicker">{"Campfire recipe" if campfire else "Recipe"}</p>
        <h1>{esc(name)}</h1>
      </div>
    </header>
    <p class="static-intro">{esc(intro)}</p>{traits(facts)}{section("Description", buff_list)}{section("Ingredients", ingredient_list)}
  </article>{open_in_app(root, "recipes", r["id"], "you")}'''

    first_buff = f' {buffs[0]}' if buffs else ''
    where = 'at your campfire' if campfire else f'by {STATION_PROSE[r["station_id"]]}'
    description = clip(f'{name} in RDR2: crafted {where} from {needs}.{first_buff}')
    kind_title = 'Campfire Recipe' if campfire else 'Recipe & Ingredients'
    return page(root=root, path=f'recipes/{slug(r["id"], "recipes")}/',
                title=f'{name}: RDR2 {kind_title} · {SITE_NAME}',
                description=description,
                crumbs=[('Crafting Guide', ''), ('Recipes', 'recipes/'),
                        (name, f'recipes/{slug(r["id"], "recipes")}/')],
                tab='recipes', body=body, csp=parts[0], theme=parts[1])


