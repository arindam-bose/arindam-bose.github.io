def load(db_path):
    con = sqlite3.connect(f'file:{db_path}?mode=ro', uri=True)
    con.row_factory = sqlite3.Row
    q = lambda sql: [dict(r) for r in con.execute(sql)]

    data = {
        'built_at': con.execute("SELECT value FROM meta WHERE key = 'built_at'").fetchone()[0],
        'ingredients': q('SELECT * FROM ingredients ORDER BY name'),
        'animals': defaultdict(list),
        'usage': defaultdict(list),
        'recipes': q('''
            SELECT r.*, st.name AS station, st.kind AS station_kind,
                   s.name AS set_name
            FROM   recipes r
            JOIN   stations st ON st.id = r.station_id
            LEFT JOIN sets s   ON s.id  = r.set_id
            ORDER  BY r.name'''),
        'ingredients_of': defaultdict(list),
    }
    for a in q('''
            SELECT ia.ingredient_id, a.name, a.link, a.bait, w.name AS weapon
            FROM   ingredient_animals ia
            JOIN   animals a ON a.id = ia.animal_id
            LEFT JOIN weapons w ON w.id = a.weapon_id
            ORDER  BY a.name'''):
        data['animals'][a['ingredient_id']].append(a)
    for u in q('''
            SELECT ri.ingredient_id, ri.qty, r.id AS recipe_id, r.name AS recipe,
                   r.repeatable, st.id AS station_id, st.name AS station,
                   loc.name AS location
            FROM   recipe_ingredients ri
            JOIN   recipes   r   ON r.id   = ri.recipe_id
            JOIN   stations  st  ON st.id  = r.station_id
            JOIN   locations loc ON loc.id = st.location_id
            ORDER  BY r.name'''):
        data['usage'][u['ingredient_id']].append(u)
    for i in q('''
            SELECT ri.recipe_id, ri.slot, ri.qty, ing.id AS ingredient_id,
                   ing.name, ing.quality
            FROM   recipe_ingredients ri
            JOIN   ingredients ing ON ing.id = ri.ingredient_id
            ORDER  BY ing.name'''):
        data['ingredients_of'][i['recipe_id']].append(i)
    con.close()
    return data


def slots(recipe, ingredients):
    """A recipe's ingredients as slots, as recipes.js groups them."""
    by_slot = defaultdict(list)
    for i in ingredients:
        by_slot[i['slot']].append(i)
    order = sorted(by_slot) if recipe['repeatable'] else list(by_slot)
    return [by_slot[s] for s in order]


