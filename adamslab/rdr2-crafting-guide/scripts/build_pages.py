def build(db_path):
    """Every file this makes, as {relative path: contents}."""
    data = load(db_path)
    parts = shell_parts()
    out = {
        'materials/index.html': materials_index(data, parts),
        'recipes/index.html': recipes_index(data, parts),
    }
    for m in data['ingredients']:
        out[f'materials/{slug(m["id"], "materials")}/index.html'] = material_page(m, data, parts)
    for r in data['recipes']:
        out[f'recipes/{slug(r["id"], "recipes")}/index.html'] = recipe_page(r, data, parts)

    pages = [''] + [p[:-len('index.html')] for p in out]
    out['sitemap.xml'] = sitemap(pages, data['built_at'])
    return out


def stale_folders(out):
    """Generated folders whose material or recipe is gone from the database."""
    keep = {Path(p).parent for p in out}
    for kind in PREFIX:
        for folder in sorted((ROOT / kind).glob('*/')):
            page_ = folder / 'index.html'
            if (folder.relative_to(ROOT) not in keep and page_.exists()
                    and MARKER in page_.read_text(encoding='utf-8')):
                yield folder


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('db', nargs='?', default=ROOT / 'data' / 'rdr2.db', type=Path)
    ap.add_argument('--check', action='store_true',
                    help='write nothing; exit 1 if any page is missing, stale or orphaned')
    args = ap.parse_args()

    out = build(args.db)
    changed = [p for p, text in out.items()
               if not (ROOT / p).exists() or (ROOT / p).read_text(encoding='utf-8') != text]
    orphans = list(stale_folders(out))

    if args.check:
        for p in changed:
            print(f'stale: {p}')
        for f in orphans:
            print(f'orphaned: {f.relative_to(ROOT)}/')
        print(f'{len(out)} files; {len(changed)} stale, {len(orphans)} orphaned')
        sys.exit(1 if changed or orphans else 0)

    for p in changed:
        (ROOT / p).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / p).write_text(out[p], encoding='utf-8')
    for f in orphans:
        shutil.rmtree(f)
    print(f'{len(out)} files; wrote {len(changed)}, removed {len(orphans)} orphaned')


if __name__ == '__main__':
    main()
