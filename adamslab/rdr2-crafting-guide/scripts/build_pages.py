def material_page(m, data, parts):
    root = '../../'
    animals = data['animals'][m['id']]
    usage = data['usage'][m['id']]
    vendor_uses = [u for u in usage if not u['repeatable']]
    fire_uses = [u for u in usage if u['repeatable']]
    name = m['name']

    # What each vendor station asks for in all, every recipe counted --
    # the app's General mode.
    demand = defaultdict(int)
    for u in vendor_uses:
        demand[u['station_id']] += u['qty']
    stations = {u['station_id']: u for u in usage}
    vendors = [STATION_PROSE[s] for s in STATION_ORDER if s in demand]

    # The sentence a search result quotes.
    kind = 'crafting recipe' if vendor_uses else 'campfire recipe'
    said = [f'{name} is used in {plural(len(usage), kind)} in Red Dead Redemption 2']
    if vendors:
        said[0] += ' -- ' + listing(
            f'{plural(sum(1 for u in vendor_uses if u["station_id"] == s), "recipe")} '
            f'for {STATION_PROSE[s]}' for s in STATION_ORDER if s in demand)
        if fire_uses:
            said[0] += f', and {plural(len(fire_uses), "recipe")} at your campfire'
    said[0] += '.'
    if len(animals) == 1:
        a = animals[0]
        if a['bait']:
            said.append(f'It comes from the {a["name"]}; catch one with {a["bait"]}.')
        elif a['weapon']:
            said.append(f'It comes from the {a["name"]}; the {a["weapon"]} takes one '
                        f'cleanly, without spoiling the {(m["body_part"] or "carcass").lower()}.')
        else:
            said.append(f'It comes from the {a["name"]}.')
    elif animals:
        shown = [a['name'] for a in animals[:4]]
        more = f' and {len(animals) - 4} more' if len(animals) > 4 else ''
        said.append(f'It comes from {len(animals)} animals, including {", ".join(shown)}{more}.')
    intro = ' '.join(said)

    only = animals[0] if len(animals) == 1 else None
    if m['source_type'] == 'animal':
        facts = [('Animal', only and web_link(only['link'], only['name'])),
                 ('Quality', quality_label(m['quality'])),
                 ('Type', esc(m['body_part'])),
                 ('Weapon', only and esc(only['weapon'])),
                 ('Bait', only and esc(only['bait']))]
    elif m['source_type'] == 'misc':
        facts = [('Source', 'Found out in the world'), ('Quality', quality_label(m['quality']))]
    else:
        facts = []

    animal_list = len(animals) > 1 and (
        '<ul class="detail-list detail-animals">' + ''.join(
            f'\n          <li><span class="what">{web_link(a["link"], a["name"])}</span>'
            + (f'<span class="how">{esc("Bait: " + a["bait"] if a["bait"] else a["weapon"])}</span>'
               if a['bait'] or a['weapon'] else '') + '</li>'
            for a in animals) + '\n        </ul>')

    recipe_list = '<ul class="detail-list detail-recipes">' + ''.join(
        f'\n          <li class="plain"><span class="what">{u["qty"]}x for '
        f'{page_link("recipes", u["recipe_id"], u["recipe"], root)}'
        f'<small>{esc(u["station"])}</small></span></li>'
        for u in usage) + '\n        </ul>'

    stock = ''.join(
        f'\n          <div class="stock-line demand">'
        f'<span class="stock-text"><span class="station">{icon(STATION_ICON.get(s))}'
        f'{esc(stations[s]["station"])}</span> needs {demand[s]}'
        + (f'<small class="from">from your {esc(stations[s]["location"])}</small>'
           if stations[s]['location'] != stations[s]['station'] else '')
        + '</span></div>'
        for s in STATION_ORDER if s in demand)

    body = f'''
  <article class="static-detail">
    <header class="detail-head">
      <div>
        <p class="detail-kicker">{esc(KIND_LABEL.get(m["source_type"], "Material"))}</p>
        <h1>{esc(name)}{stars(m["quality"])}</h1>
      </div>
    </header>
    <p class="static-intro">{esc(intro)}</p>{traits(facts)}{section("Animals", animal_list)}{section("Recipes used in", recipe_list)}{section("Vendors", stock and f'<div class="detail-stock">{stock}</div>')}
  </article>{open_in_app(root, "materials", m["id"], "it")}'''

    where = listing(vendors + (['your campfire'] if fire_uses and vendors else []))
    description = clip(f'{name} in RDR2: used in {plural(len(usage), "recipe" if vendors else kind)}'
                       f'{" (" + where + ")" if where else ""}. '
                       + (said[1] + ' ' if len(said) > 1 else '')
                       + 'Every recipe it goes into, and how much each one needs.')
    return page(root=root, path=f'materials/{slug(m["id"], "materials")}/',
                title=f'{name}: RDR2 Uses & Recipes · {SITE_NAME}',
                description=description,
                crumbs=[('Crafting Guide', ''), ('Materials', 'materials/'),
                        (name, f'materials/{slug(m["id"], "materials")}/')],
                tab='materials', body=body, csp=parts[0], theme=parts[1])


